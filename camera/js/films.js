export const FILM_BY_ID = Object.fromEntries(FILMS.map((f) => [f.id, f]));

// Frühere Filme der App (ersetzt durch die spektralen Filme): alte Fotos,
// Looks und Einstellungen werden auf den nächsten echten Film umgestellt.
export const FILM_ALIASES = {
  pastell400: 'sp_portra400',
  aurum200: 'sp_gold200',
  alltag400: 'sp_ultramax400',
  vivid100: 'sp_ektar100',
  kino500t: 'sp_vision500t',
  kino250d: 'sp_vision250d',
  chrom50: 'sp_velvia100',
  chrom100: 'sp_provia100f',
};
const LEGACY_NAMES = {
  pastell400: 'Pastell 400', aurum200: 'Aurum 200', alltag400: 'Alltag 400', vivid100: 'Vivid 100',
  kino500t: 'Kino 500T', kino250d: 'Kino 250D', chrom50: 'Chrom 50', chrom100: 'Chrom 100',
};

export function resolveFilmId(id) {
  return FILM_BY_ID[id] ? id : FILM_ALIASES[id] ?? FILMS[0].id;
}

export function getFilm(id) {
  return FILM_BY_ID[resolveFilmId(id)];
}

// Anzeigename für bereits entwickelte Fotos (auch mit früheren Filmen).
export function filmDisplayName(id) {
  return LEGACY_NAMES[id] ?? getFilm(id).name;
}
