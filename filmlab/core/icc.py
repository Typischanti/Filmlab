"""Erzeugung von ICC-v2-Matrix/TRC-Profilen für die Ausgabefarbräume.

Pillow bringt nur ein sRGB-Profil mit; für Adobe-RGB-kompatible, ProPhoto- und
Rec.2020-Ausgaben erzeugen wir standardkonforme Display-Profile selbst
(Klasse 'mntr', PCS XYZ, Kolorante Bradford-adaptiert auf D50).
Die Profile werden in den Tests mit LittleCMS (Pillow ImageCms) geladen und
gegen die Matrix-Pipeline verifiziert.
"""
from __future__ import annotations

import struct
from functools import lru_cache

import numpy as np

from .colorspace import PCS_D50_XYZ, SPACES, RGBColorSpace, adaptation_matrix, decode


def _s15f16(v: float) -> bytes:
    return struct.pack(">i", int(round(v * 65536.0)))


def _xyz_tag(xyz) -> bytes:
    return b"XYZ " + b"\0" * 4 + b"".join(_s15f16(c) for c in xyz)


def _desc_tag(text: str) -> bytes:
    ascii_ = text.encode("ascii", "replace") + b"\0"
    data = b"desc" + b"\0" * 4 + struct.pack(">I", len(ascii_)) + ascii_
    data += struct.pack(">II", 0, 0)  # Unicode: Sprache, Länge
    data += struct.pack(">HB", 0, 0) + b"\0" * 67  # ScriptCode
    return data


def _text_tag(text: str) -> bytes:
    return b"text" + b"\0" * 4 + text.encode("ascii", "replace") + b"\0"


def _curve_tag(space: RGBColorSpace) -> bytes:
    if space.transfer == "linear":
        return b"curv" + b"\0" * 4 + struct.pack(">I", 0)  # Identität
    if space.transfer == "gamma":
        return b"curv" + b"\0" * 4 + struct.pack(">I", 1) + struct.pack(">H", int(round(space.gamma * 256)))
    n = 1024
    x = np.linspace(0.0, 1.0, n, dtype=np.float64)
    y = np.clip(decode(x.astype(np.float32), space).astype(np.float64), 0.0, 1.0)
    table = np.round(y * 65535.0).astype(">u2").tobytes()
    return b"curv" + b"\0" * 4 + struct.pack(">I", n) + table


def _pad4(b: bytes) -> bytes:
    return b + b"\0" * (-len(b) % 4)


@lru_cache(maxsize=None)
def icc_profile_bytes(space_key: str) -> bytes:
    """Liefert ein ICC-v2-Profil (bytes) für den gegebenen Ausgabefarbraum."""
    space = SPACES[space_key]
    m = space.to_xyz
    if space.white != (0.3457, 0.3585):
        m = adaptation_matrix(space.white_xyz, PCS_D50_XYZ) @ m
    trc = _pad4(_curve_tag(space))
    tags: list[tuple[bytes, bytes]] = [
        (b"desc", _pad4(_desc_tag(f"FilmLab {space.label}"))),
        (b"cprt", _pad4(_text_tag("No copyright, use freely (generated by FilmLab)"))),
        (b"wtpt", _xyz_tag(space.white_xyz)),
        (b"rXYZ", _xyz_tag(m[:, 0])),
        (b"gXYZ", _xyz_tag(m[:, 1])),
        (b"bXYZ", _xyz_tag(m[:, 2])),
        (b"rTRC", trc),
        (b"gTRC", trc),
        (b"bTRC", trc),
    ]
    table_size = 4 + 12 * len(tags)
    offset = 128 + table_size
    table = struct.pack(">I", len(tags))
    data = b""
    shared: dict[bytes, int] = {}
    for sig, payload in tags:
        if payload in shared:
            off = shared[payload]
        else:
            off = offset + len(data)
            shared[payload] = off
            data += payload
        table += sig + struct.pack(">II", off, len(payload))
    size = 128 + table_size + len(data)
    header = struct.pack(">I", size)
    header += b"\0" * 4  # preferred CMM
    header += struct.pack(">I", 0x02100000)  # Version 2.1
    header += b"mntr" + b"RGB " + b"XYZ "
    header += struct.pack(">6H", 2026, 1, 1, 0, 0, 0)
    header += b"acsp" + b"\0" * 4  # Plattform
    header += struct.pack(">I", 0)  # Flags
    header += b"\0" * 4 + b"\0" * 4  # Hersteller, Modell
    header += b"\0" * 8  # Attribute
    header += struct.pack(">I", 0)  # Rendering Intent: perzeptiv
    header += b"".join(_s15f16(c) for c in PCS_D50_XYZ)
    header += b"\0" * 4  # Creator
    header += b"\0" * 16  # Profile-ID
    header += b"\0" * 28
    assert len(header) == 128
    return header + table + data
